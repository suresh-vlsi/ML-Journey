import numpy as np


# ============================================================
# 1. SIGMOID
# ============================================================

def sigmoid(z):
    return 1 / (1 + np.exp(-z))


# ============================================================
# 2. INPUT
# ============================================================

x = np.array([
    [2.0],
    [3.0]
])


# ============================================================
# 3. HIDDEN LAYER PARAMETERS
# ============================================================

W1 = np.array([
    [0.5, 0.8],
    [0.2, -0.4],
    [1.0, 0.3]
])

b1 = np.array([
    [0.2],
    [0.1],
    [-0.5]
])


# ============================================================
# 4. OUTPUT LAYER PARAMETERS
# ============================================================

W2 = np.array([
    [0.7, -0.5, 0.9]
])

b2 = np.array([
    [0.1]
])


# ============================================================
# 5. HIDDEN LAYER
# ============================================================

z1 = W1 @ x + b1

a1 = sigmoid(z1)


# ============================================================
# 6. OUTPUT LAYER
# ============================================================

z2 = W2 @ a1 + b2

y_hat = sigmoid(z2)


# ============================================================
# 7. PRINT EVERYTHING
# ============================================================

print("INPUT")
print("x =")
print(x)


print("\nHIDDEN LAYER")
print("W1 =")
print(W1)

print("\nb1 =")
print(b1)

print("\nz1 =")
print(z1)

print("\na1 =")
print(a1)


print("\nOUTPUT LAYER")
print("W2 =")
print(W2)

print("\nb2 =")
print(b2)

print("\nz2 =")
print(z2)

print("\ny_hat =")
print(y_hat)
import numpy as np


# ==========================================
# Dataset
# ==========================================

X = np.array([
    [1, 1],
    [1.5, 1],
    [2, 1.5],
    [2.5, 2],

    [7, 7],
    [8, 7],
    [8, 8],
    [9, 8]
])


y = np.array([
    0,
    0,
    0,
    0,

    1,
    1,
    1,
    1
])


# ==========================================
# Parameters
# ==========================================

w = np.array([2.0, 2.0])
b = -10.0


# ==========================================
# Sigmoid
# ==========================================

def sigmoid(z):
    return 1 / (1 + np.exp(-z))


# ==========================================
# Linear score
# ==========================================

z = X @ w + b


# ==========================================
# Probability
# ==========================================

p = sigmoid(z)


# ==========================================
# Prediction
# ==========================================

y_pred = (p >= 0.5).astype(int)


# ==========================================
# Output
# ==========================================

print("Linear scores:")
print(z)

print("\nProbabilities:")
print(p)

print("\nPredictions:")
print(y_pred)

print("\nActual labels:")
print(y)
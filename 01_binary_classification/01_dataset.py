import numpy as np


# ==========================================
# Dataset
# ==========================================

X = np.array([
    [1, 1],
    [1.5, 1],
    [2, 1.5],
    [2.5, 2],

    [7, 7],
    [8, 7],
    [8, 8],
    [9, 8]
])


# ==========================================
# Labels
# ==========================================

y = np.array([
    0,
    0,
    0,
    0,

    1,
    1,
    1,
    1
])


# ==========================================
# Model parameters
# ==========================================

w = np.array([0.5, 0.5])
b = -5.0


# ==========================================
# Linear model
# z = Xw + b
# ==========================================

z = X @ w + b


# ==========================================
# Prediction
# ==========================================

y_pred = (z >= 0).astype(int)


# ==========================================
# Display
# ==========================================

print("X:")
print(X)

print("\ny:")
print(y)

print("\nX shape:")
print(X.shape)

print("\ny shape:")
print(y.shape)

print("\nWeights:")
print(w)

print("\nBias:")
print(b)

print("\nLinear scores:")
print(z)

print("\nPredictions:")
print(y_pred)
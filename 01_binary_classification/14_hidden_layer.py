import numpy as np


# ============================================================
# INPUT
# ============================================================

x = np.array([
    [2.0],
    [3.0]
])


# ============================================================
# WEIGHTS
#
# 3 neurons
# 2 inputs per neuron
# ============================================================

W = np.array([
    [0.5, 0.8],
    [0.2, -0.4],
    [1.0, 0.3]
])


# ============================================================
# BIAS
# ============================================================

b = np.array([
    [0.2],
    [0.1],
    [-0.5]
])


# ============================================================
# LINEAR TRANSFORMATION
# ============================================================

z = W @ x + b


# ============================================================
# SIGMOID
# ============================================================

a = 1 / (1 + np.exp(-z))


# ============================================================
# RESULTS
# ============================================================

print("Input:")
print(x)

print("\nWeight matrix:")
print(W)

print("\nBias:")
print(b)

print("\nWeighted sums:")
print(z)

print("\nNeuron outputs:")
print(a)
import numpy as np


# ==========================================
# Dataset
# ==========================================

X = np.array([
    [1, 1],
    [1.5, 1],
    [2, 1.5],
    [2.5, 2],

    [7, 7],
    [8, 7],
    [8, 8],
    [9, 8]
])


y = np.array([
    0,
    0,
    0,
    0,
    1,
    1,
    1,
    1
])


# ==========================================
# Parameters
# ==========================================

w = np.array([1.0, 1.0])
b = -5.0


# ==========================================
# Sigmoid
# ==========================================

def sigmoid(z):
    return 1 / (1 + np.exp(-z))


# ==========================================
# Binary Cross-Entropy
# ==========================================

def binary_cross_entropy(y, p):

    epsilon = 1e-15

    p = np.clip(p, epsilon, 1 - epsilon)

    loss = -(y * np.log(p) +
             (1 - y) * np.log(1 - p))

    return np.mean(loss)


# ==========================================
# Forward pass
# ==========================================

z = X @ w + b

p = sigmoid(z)


# ==========================================
# Loss
# ==========================================

loss = binary_cross_entropy(y, p)


# ==========================================
# Output
# ==========================================

print("Scores:")
print(z)

print("\nProbabilities:")
print(p)

print("\nActual labels:")
print(y)

print("\nAverage BCE loss:")
print(loss)
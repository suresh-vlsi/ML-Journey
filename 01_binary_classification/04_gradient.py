import numpy as np


# ==========================================
# Dataset
# ==========================================

X = np.array([
    [1, 1],
    [1.5, 1],
    [2, 1.5],
    [2.5, 2],

    [7, 7],
    [8, 7],
    [8, 8],
    [9, 8]
])

y = np.array([
    0,
    0,
    0,
    0,
    1,
    1,
    1,
    1
])


# ==========================================
# Parameters
# ==========================================

w = np.array([1.0, 1.0])
b = -5.0


# ==========================================
# Sigmoid
# ==========================================

def sigmoid(z):
    return 1 / (1 + np.exp(-z))


# ==========================================
# Forward pass
# ==========================================

z = X @ w + b

p = sigmoid(z)


# ==========================================
# Gradient
# ==========================================

error = p - y

dw = (X.T @ error) / len(X)

db = np.mean(error)


# ==========================================
# Output
# ==========================================

print("Scores:")
print(z)

print("\nProbabilities:")
print(p)

print("\nActual labels:")
print(y)

print("\nError (p - y):")
print(error)

print("\nGradient dw:")
print(dw)

print("\nGradient db:")
print(db)
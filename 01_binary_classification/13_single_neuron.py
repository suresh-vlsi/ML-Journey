import numpy as np


# ============================================================
# INPUT
# ============================================================

x = np.array([2.0, 3.0])


# ============================================================
# WEIGHTS
# ============================================================

w = np.array([0.5, 0.8])


# ============================================================
# BIAS
# ============================================================

b = 0.2


# ============================================================
# LINEAR COMPUTATION
# ============================================================

z = np.dot(x, w) + b


# ============================================================
# SIGMOID ACTIVATION
# ============================================================

a = 1 / (1 + np.exp(-z))


# ============================================================
# RESULTS
# ============================================================

print("Input x:", x)

print("Weights w:", w)

print("Bias b:", b)

print("Weighted sum z:", z)

print("Neuron output a:", a)